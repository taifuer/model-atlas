import { test, expect } from '@playwright/test';

for (const language of ['zh', 'en']) {
  test(`${language}: robot actions retain their task and announcement scope`, async ({ page }) => {
    await page.goto(`${language === 'en' ? '/en/' : '/'}index.html?task=robot-action`);
    const listURL = page.url();
    await expect(page.locator('#task-select')).toHaveValue('robot-action');
    const release = page.locator('#release-groot-2');
    await expect(release).toBeVisible();
    await expect(page.locator('.release-card')).toHaveCount(1);
    await expect(release.locator('.fact-chip')).toHaveCount(0);
    const chartTotal = await page.locator('.annual-bar').evaluateAll(bars => bars.reduce((sum, bar) => sum + Number(bar.dataset.count), 0));
    expect(chartTotal).toBe(1);
    await release.locator('.card-title button').click();
    await expect(page.locator('.detail-overview')).toContainText(language === 'en' ? 'December' : '12 月');
    await expect(page.locator('.detail-overview')).toContainText(language === 'en' ? 'announcement' : '公告');
    await page.keyboard.press('Escape');
    await expect(page).toHaveURL(listURL);
    await expect(page.locator('#detail-dialog')).not.toBeVisible();
    await page.locator('#openness-select').selectOption('open');
    await expect(release).toHaveCount(0);
    await page.locator('#openness-select').selectOption('closed');
    await expect(release).toBeVisible();
    await page.reload();
    await expect(page.locator('#task-select')).toHaveValue('robot-action');
    await expect(release).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  });

  test(`${language}: video task, chart, input and access filters share URL state`, async ({ page }) => {
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${language === 'en' ? '/en/' : '/'}index.html?task=video-generation`);
    await expect(page.locator('#task-select')).toHaveValue('video-generation');
    await expect(page.locator('#release-seedance-2-5')).toBeAttached();
    await expect(page.locator('#release-gpt-4o')).toHaveCount(0);
    await expect(page.locator('.company-chip.is-empty:visible')).toHaveCount(0);
    const videoCount = await page.locator('.release-card').count();
    const chartTotal = await page.locator('.annual-bar').evaluateAll(bars => bars.reduce((sum, bar) => sum + Number(bar.dataset.count), 0));
    expect(chartTotal).toBe(videoCount);
    await page.locator('#category-select').selectOption('text');
    await page.locator('#openness-select').selectOption('open');
    await expect(page.locator('#release-hunyuan-video')).toBeAttached();
    await expect(page.locator('#release-seedance-2-5')).toHaveCount(0);
    await page.reload();
    await expect(page.locator('#task-select')).toHaveValue('video-generation');
    await expect(page.locator('#category-select')).toHaveValue('text');
    await expect(page.locator('#openness-select')).toHaveValue('open');
    await page.locator('#reset-filters').click();
    await expect(page.locator('#task-select')).toHaveValue('all');
    await expect(page.locator('[data-show-more]')).toBeVisible();
    await page.locator('[data-show-all]').click();
    await expect(page.locator('#release-gpt-4o')).toBeAttached();
    await page.goBack();
    await expect(page.locator('#task-select')).toHaveValue('video-generation');
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
    expect(errors).toEqual([]);
  });

  test(`${language}: video chips keep variant limits and distinguish enhanced output`, async ({ page }) => {
    await page.goto(`${language === 'en' ? '/en/' : '/'}index.html?task=video-generation`);
    const seedance = page.locator('#release-seedance-2-5');
    await expect(seedance.locator('.fact-chip')).toContainText(['30']);
    await expect(page.locator('[data-detail-section="pricing"], [data-detail-section="scores"]')).toHaveCount(0);
    await seedance.locator('.fact-chip').first().click();
    await expect(page.locator('#specs-title')).toBeFocused();
    await expect(page.locator('.detail-specs')).toContainText(language === 'en' ? 'Maximum generation duration' : '单次生成时长上限');
    const standard = page.locator('.spec-variant').filter({ hasText: 'doubao-seedance-2-5-260628' });
    const flash = page.locator('.spec-variant').filter({ hasText: 'doubao-seedance-2-5-flash-261115' });
    const resolution = language === 'en' ? 'Output resolution' : '输出分辨率';
    await expect(standard.locator('.spec-grid > div').filter({ hasText: resolution }).locator('dd')).toHaveText('480p · 720p · 1080p · 4K');
    await expect(flash.locator('.spec-grid > div').filter({ hasText: resolution }).locator('dd')).toHaveText('480p · 720p');
    await page.keyboard.press('Escape');
    const hailuo = page.locator('#release-hailuo-01');
    await expect(hailuo.locator('.fact-chip .fact-model')).toHaveText(['Video-01', 'Video-01']);
    await expect(hailuo.locator('.fact-chip')).toContainText([language === 'en' ? '6 s' : '6 秒', '720p']);
    await hailuo.locator('[data-detail-section="history"]').click();
    const second = page.locator('#history-hailuo-02');
    await second.locator('summary').click();
    await expect(second.locator('.history-name')).toHaveText('Hailuo 02');
    await expect(second.locator('.history-date time')).toHaveAttribute('datetime', '2025-06-18');
    const hd = second.locator('.spec-variant').filter({ hasText: 'Hailuo 02 · 768p' });
    await expect(hd.locator('.spec-grid')).toContainText(language === 'en' ? '10 seconds' : '10 秒');
    const fullHD = second.locator('.spec-variant').filter({ hasText: 'Hailuo 02 · 1080p' });
    await expect(fullHD.locator('.spec-grid')).toContainText(language === 'en' ? '6 seconds' : '6 秒');
    await expect(fullHD.locator('.spec-grid')).not.toContainText(language === 'en' ? '10 seconds' : '10 秒');
    await page.keyboard.press('Escape');
    await page.locator('#release-gemini-omni-1-2-flash [data-detail-section="history"]').click();
    const omni = page.locator('#history-gemini-omni-1-1-flash');
    await omni.locator('summary').click();
    await expect(omni.locator('.history-name')).toHaveText('Gemini Omni 1.1 Flash');
    const outputs = omni.locator('.detail-specs .spec-grid > div');
    await expect(outputs.filter({ hasText: language === 'en' ? 'Output resolution' : '输出分辨率' }).locator('dd')).toHaveText('360p · 720p');
    await expect(outputs.filter({ hasText: language === 'en' ? 'Upscaled output' : '升采样输出' }).locator('dd')).toHaveText('1080p · 4K');
    await page.keyboard.press('Escape');
    await page.locator('[data-view="compact"]').click();
    await expect(page.locator('.fact-chip, .card-tags')).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  });
}
